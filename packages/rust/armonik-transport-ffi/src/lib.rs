/// Result codes returned by every entry point in this crate.
///
/// `0` is success; everything else is negative. There is no positive space: this ABI carries no
/// gRPC status, and an HTTP status is a response header, not a result code.
pub mod status {
    /// The operation succeeded.
    pub const OK: i32 = 0;
    /// A pointer argument that must not be null was null.
    pub const NULL_ARGUMENT: i32 = -1;
    /// A byte buffer was not valid UTF-8 where UTF-8 was required.
    pub const INVALID_UTF8: i32 = -2;
    /// The client configuration was rejected; see the returned error message.
    pub const INVALID_CONFIG: i32 = -3;
    /// The request never reached the server: no connection, or the connection failed before any
    /// response header arrived. See the message on the `COMPLETED` event.
    pub const CONNECTION_FAILED: i32 = -4;
    /// The handle passed to a call has already been freed, or was never valid.
    pub const INVALID_HANDLE: i32 = -5;
    /// The request is not in a state that allows the operation: a second read or write armed while
    /// one is still outstanding, a write after `ak_request_close_send`, or an operation on a
    /// request that has already completed.
    pub const INVALID_STATE: i32 = -6;
    /// Something inside this crate failed in a way that is not the caller's doing; see the message.
    pub const INTERNAL: i32 = -8;
    /// A panic was caught at the FFI boundary, or inside the task driving a request. This is always
    /// a bug in this crate; the message carries whatever the panic payload could be turned into.
    pub const INTERNAL_PANIC: i32 = -9;
    /// The request was cancelled through [`crate::ak_request_cancel`], or by
    /// [`crate::ak_request_release`] before it had completed.
    pub const CANCELLED: i32 = -10;
    /// The configured `Timeout` elapsed while the request was still in flight.
    pub const TIMEOUT: i32 = -11;
    /// The connection failed after the response headers had arrived: a reset stream, a broken
    /// connection, a protocol error. See the message on the `COMPLETED` event.
    pub const TRANSPORT: i32 = -12;
}

/// The `kind` argument of [`ak_request_on_event`].
///
/// [`ak_request_on_event`]: crate::request::ak_request_on_event
pub mod event {
    /// The response headers arrived. `payload` is a key/value blob; the HTTP status is in it under
    /// the `:status` key, as decimal ASCII. `code` is [`crate::status::OK`].
    ///
    /// Always the first event of a successful request, and never emitted more than once.
    pub const RESPONSE_HEADERS: i32 = 1;
    /// The chunk armed by [`crate::ak_request_write`] has been handed to the connection. `payload`
    /// is empty, `code` is [`crate::status::OK`]. It does not mean the bytes reached the server,
    /// only that this crate no longer needs the caller's buffer and one more write may be armed.
    pub const WRITE_DONE: i32 = 2;
    /// The read armed by [`crate::ak_request_read`] produced body bytes. `payload` is the chunk,
    /// borrowed for the duration of the call; `code` is [`crate::status::OK`].
    ///
    /// A chunk is whatever the connection delivered as one DATA frame's worth of body, not a
    /// message: there is no framing at this level, so a reader must handle any split.
    pub const READ_DONE: i32 = 3;
    /// The request is over, and no further callback will be made for it.
    ///
    /// `code` is [`crate::status::OK`] when the response ended cleanly, and `payload` is then the
    /// trailers as a key/value blob - possibly empty, which is what a clean early end of stream
    /// looks like. Otherwise `code` is one of the negative statuses and `payload` is the failure,
    /// rendered as a UTF-8 message with its whole cause chain flattened into it.
    pub const COMPLETED: i32 = 4;
}
