/// Result codes returned by every entry point in this crate.
///
/// `0` is success. A positive value is an [`armonik_transport::reexports::tonic::Code`] as defined
/// by gRPC, returned when the failure came from the RPC itself. A negative value is local to this
/// crate — a problem in the FFI layer itself, before or outside of any gRPC status.
pub mod status {
    /// The call succeeded.
    pub const OK: i32 = 0;
    /// A pointer argument that must not be null was null.
    pub const NULL_ARGUMENT: i32 = -1;
    /// A byte buffer was not valid UTF-8 where UTF-8 was required.
    pub const INVALID_UTF8: i32 = -2;
    /// The client configuration was rejected; see the returned error message.
    pub const INVALID_CONFIG: i32 = -3;
    /// Connecting to the endpoint failed; see the returned error message.
    pub const CONNECTION_FAILED: i32 = -4;
    /// The handle passed to a call has already been freed, or was never valid.
    pub const INVALID_HANDLE: i32 = -5;
    /// The call is not in a state that allows the requested operation, e.g. sending after
    /// [`crate::ak_call_close_send`], or a second concurrent call to a function that is not safe
    /// to call concurrently with itself.
    pub const INVALID_STATE: i32 = -6;
    /// A send queue is full; retry after the event handle is signalled.
    pub const WOULD_BLOCK: i32 = -7;
    /// An operating-system resource this crate needed could not be obtained; see the returned error
    /// message.
    pub const INTERNAL: i32 = -8;
    /// A panic was caught at the FFI boundary. This is always a bug in this crate; the message
    /// carries whatever the panic payload could be turned into.
    pub const INTERNAL_PANIC: i32 = -9;

    /// Turn a gRPC status code into the positive status this crate reports for it.
    pub(crate) fn from_grpc(code: armonik_transport::reexports::tonic::Code) -> i32 {
        code as i32
    }
}
