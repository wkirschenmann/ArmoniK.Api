//! C ABI over the ArmoniK Rust transport, for host applications that cannot link Rust directly.
//!
//! # Scope
//!
//! This crate is deliberately thin. It knows nothing about ArmoniK's services or RPCs — every call
//! is addressed by an opaque method path and moves opaque bytes. Configuration parsing, TLS, proxy
//! handling and retry policy all live in
//! [`armonik_transport`](https://docs.rs/armonik-transport); this crate only adapts that connection
//! layer to a C ABI. It is never published to a registry: it is built as a `cdylib` and shipped
//! alongside whatever binds to it.
//!
//! # Design
//!
//! Nothing here calls back into the caller's code — no function pointer ever crosses the boundary
//! inwards. This crate buffers messages, logs and the final status into bounded queues that the
//! caller drains by polling, and signals an OS event when there is something new to read. That
//! removes every hazard that would come with a foreign runtime having to attach one of its threads
//! to answer a call from here, and with a caller-supplied callback being required not to panic,
//! block or re-enter.
//!
//! See `include/armonik_transport_ffi.h` for the full contract, generated by `cbindgen` from the
//! `pub extern "C"` items below and committed so an ABI change shows up in review.
//!
//! # Safety discipline
//!
//! - Every `extern "C"` entry point is wrapped by one of this crate's internal
//!   `catch_unwind_status`/`catch_unwind_status_only`/`catch_unwind_void` helpers, so a panic can
//!   never cross the ABI boundary.
//! - Every allocation handed to the caller travels as an [`error::ak_bytes`] and must be released
//!   through [`error::ak_bytes_free`] exactly once.
//! - Every opaque handle ([`client::ak_client`], [`call::ak_call`]) is only ever touched behind a
//!   raw pointer that the caller must not alias or use after the matching `_free` call; see each
//!   type's documentation for its exact contract.

