//! C ABI over the ArmoniK Rust transport, for host applications that cannot link Rust directly.
//!
//! # Scope
//!
//! This crate speaks HTTP, not gRPC. A request is opened with a set of headers, bytes are streamed
//! in both directions, and headers, data and trailers come back. There is no notion here of a call
//! shape, of a `grpc-status`, of message framing or of retry: those belong to whatever gRPC stack
//! the host application already has, and this crate is the transport underneath it. Configuration
//! parsing, TLS, mTLS and proxy handling all live in
//! [`armonik_transport`](https://docs.rs/armonik-transport); this crate only adapts that connection
//! layer to a C ABI.
//!
//! # The reactor contract
//!
//! One event callback per request, invoked by this crate. Three rules, and everything else follows
//! from them:
//!
//! 1. **Nothing arrives unarmed.** [`ak_request_read`] arms exactly one read, which produces
//!    exactly one event: `READ_DONE` with the bytes, or `COMPLETED`. [`ak_request_write`] arms
//!    exactly one write, which produces `WRITE_DONE`. At most one read and one write may be armed
//!    at a time on a request; arming a second returns [`status::INVALID_STATE`].
//! 2. **`COMPLETED` exactly once, and last.** If [`ak_request_start`] returns [`status::OK`], a
//!    `COMPLETED` event always follows, whatever happens - cancellation, a connection failure, a
//!    panic inside this crate. If `start` returns an error, no event ever arrives. After
//!    `COMPLETED` no callback is ever made again for that request, so that is where - and only
//!    there - the caller releases whatever it rooted for `ctx`. Releasing the handle does not end
//!    that obligation; the terminal event does.
//! 3. **No callback during an inbound call.** Every function here posts a command and returns;
//!    events are emitted from this crate's own runtime threads. There is no re-entrance, and
//!    delivery is serialised per request, so a caller demultiplexing events needs no lock of its
//!    own.
//!
//! The event payload is **borrowed** for the duration of the invocation: copy what you need before
//! returning. Nothing on the event path is ever freed by the caller.
//!
//! See `include/armonik_transport_ffi.h` for the full contract, generated by `cbindgen` from the
//! `pub extern "C"` items below and committed so an ABI change shows up in review.
//!
//! # Safety discipline
//!
//! - Every `extern "C"` entry point is wrapped by one of this crate's internal
//!   `catch_unwind_status`/`catch_unwind_status_only`/`catch_unwind_void` helpers, so a panic can
//!   never cross the ABI boundary.
//! - Every allocation handed to the caller travels as an [`error::ak_bytes`] and must be released
//!   through [`error::ak_bytes_free`] exactly once. Only synchronous out-parameters produce one;
//!   the event path never does.
//! - Every opaque handle ([`client::ak_client`], [`request::ak_request`]) is reference-counted.
//!   `_release` gives up one reference; the object lives until the last one goes, so releasing a
//!   handle while another thread is mid-call is well-defined. What is never allowed is using a
//!   handle after your own `_release`.

